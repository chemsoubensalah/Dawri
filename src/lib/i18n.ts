export const dicts: Record<Lang, Dict> = { ar, fr };

export function t(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  let s: string = dicts[lang][key] ?? dicts.ar[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function isLang(v: unknown): v is Lang {
  return v === "ar" || v === "fr";
}

export function dirOf(lang: Lang) {
  return lang === "ar" ? "rtl" : "ltr";
}

/** يحوّل رمز خطأ من الخادم إلى نصّ. */
export function errorText(lang: Lang, code: string | undefined): string {
  const key = `err_${code}` as DictKey;
  return key in dicts.ar ? t(lang, key) : t(lang, "err_generic");
}
